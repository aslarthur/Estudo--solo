#TIPOS DE VARIÁVEIS

#str
nome = "Arthur" # str = string, usado para representar textos

#int
idade = 11 #int = integer, usado para representar números inteiros (sem casas decimais)

#float
dinheiro_na_conta = 51.40 #float = usado para representar números com casas decimais

#bool
esta_estudando = True #bool = boolean, para representar se um valor é True (verdadeiro) ou False (falso)

print (type (nome))
print (type (idade))
print (type (dinheiro_na_conta))
print (type (esta_estudando))

print (f"A variável {nome} (nome) é do tipo:",type (nome))
print (f"A variável {idade} (idade) é do tipo:",type (idade))
print (f"A variável {dinheiro_na_conta} (dinheiro) é do tipo:",type (dinheiro_na_conta))
print (f"A váriavel {esta_estudando} (estudando) é do tipo:",type (esta_estudando))

