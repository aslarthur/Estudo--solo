#Peça 2 números ao usuário, e em seguida, exiba a soma e a subtração deles
numero1 = float(input("Digite um número: "))
numero2 = float(input("Digite outro número: "))
soma = numero1 + numero2
subtracao = numero1 - numero2
print (f"A soma do número {numero1} e do {numero2} é {soma:.2f}")
print (f"A subtração do número {numero1} e do {numero2} é {subtracao:.2f}")